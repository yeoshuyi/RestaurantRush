/**
 * AST log generator for verifying the class diagram.
 *
 * Parses and type-checks every .java file under src/ with the JDK's own compiler API
 * (com.sun.source.tree + javax.lang.model, no third-party libraries), then writes a
 * human-readable log of every type, its fields, constructors and methods, and the
 * relationships between types (generalization, realization, association, dependency,
 * nesting). The log is meant to be compared against class_diagram.pdf, by hand or with AI.
 *
 * Usage (from repo root, JDK 17+):
 *   java tests/AstRunner.java [srcDir] [logfile]
 * Defaults: src -> tests/class_diagram.ast.log
 */
public class AstRunner {

    private static Trees trees;
    private static Types types;
    private static Elements elements;

    /** Types declared in the parsed sources (top-level and member types only). */
    private static final Set<TypeElement> project = new HashSet<>();
    /** owner -> target -> reasons, for dependencies found in signatures and bodies. */
    private static final Map<String, Map<String, Set<String>>> deps = new TreeMap<>();
    /** "Owner#field" keys of fields that are initialised with a new object. */
    private static final Set<String> creates = new HashSet<>();

    public static void main(String[] args) throws Exception {
        Path src = Paths.get(args.length > 0 ? args[0] : "src");
        Path logFile = Paths.get(args.length > 1 ? args[1] : "tests/class_diagram.ast.log");

        List<CompilationUnitTree> units = parse(src);
        for (CompilationUnitTree cu : units) {
            new TypeCollector().scan(cu, null);
        }
        for (CompilationUnitTree cu : units) {
            new BodyScanner().scan(cu, null);
        }

        List<TypeElement> sorted = project.stream()
                .sorted(Comparator.comparing(t -> t.getQualifiedName().toString()))
                .collect(Collectors.toList());
        for (TypeElement t : sorted) {
            collectSignatureDeps(t);
        }

        StringBuilder out = new StringBuilder();
        out.append("# AST class-diagram log of ").append(slash(src)).append(" (")
                .append(sorted.size()).append(" types), generated by tests/AstRunner.java\n");
        out.append("# Visibility: + public, - private, # protected, ~ package-private\n");
        out.append("# Relations:  --|> extends, ..|> implements, --> association (field),\n");
        out.append("#             ..> dependency (used, not stored), +-- nested type\n");
        out.append("# [creates] = the field is assigned a new object in its declaration or a constructor\n\n");

        for (TypeElement t : sorted) {
            writeType(out, t);
        }
        int relations = writeRelationships(out, sorted);
        out.append("\n# ").append(sorted.size()).append(" types, ").append(relations).append(" relationships\n");

        if (logFile.getParent() != null) {
            Files.createDirectories(logFile.getParent());
        }
        Files.writeString(logFile, out.toString());
        System.out.println("AST log written to " + logFile + " (" + sorted.size() + " types, "
                + relations + " relationships)");
    }

    // ---------------------------------------------------------------- parsing

    private static List<CompilationUnitTree> parse(Path src) throws IOException {
        List<Path> files;
        try (Stream<Path> walk = Files.walk(src)) {
            files = walk.filter(p -> p.toString().endsWith(".java")).sorted().collect(Collectors.toList());
        }
        JavaCompiler javac = ToolProvider.getSystemJavaCompiler();
        DiagnosticCollector<JavaFileObject> diags = new DiagnosticCollector<>();
        StandardJavaFileManager fm = javac.getStandardFileManager(diags, null, null);
        JavacTask task = (JavacTask) javac.getTask(null, fm, diags, List.of("-proc:none"), null,
                fm.getJavaFileObjectsFromPaths(files));

        List<CompilationUnitTree> units = new ArrayList<>();
        task.parse().forEach(units::add);
        task.analyze();

        boolean failed = false;
        for (Diagnostic<? extends JavaFileObject> d : diags.getDiagnostics()) {
            if (d.getKind() == Diagnostic.Kind.ERROR) {
                System.err.println(d);
                failed = true;
            }
        }
        if (failed) {
            throw new IllegalStateException("source does not compile; fix errors above first");
        }

        trees = Trees.instance(task);
        types = task.getTypes();
        elements = task.getElements();
        return units;
    }

    /** First pass: register every named top-level and member type. */
    private static class TypeCollector extends TreePathScanner<Void, Void> {
        @Override
        public Void visitClass(ClassTree node, Void v) {
            if (trees.getElement(getCurrentPath()) instanceof TypeElement te
                    && (te.getNestingKind() == NestingKind.TOP_LEVEL || te.getNestingKind() == NestingKind.MEMBER)) {
                project.add(te);
            }
            return super.visitClass(node, v);
        }
    }

    /** Second pass: find what each type uses inside method bodies and initialisers. */
    private static class BodyScanner extends TreePathScanner<Void, Void> {
        private final Deque<TypeElement> owners = new ArrayDeque<>();
        private boolean inConstructor;

        @Override
        public Void visitClass(ClassTree node, Void v) {
            Element e = trees.getElement(getCurrentPath());
            boolean named = e instanceof TypeElement && project.contains(e);
            if (named) {
                owners.push((TypeElement) e);
            }
            try {
                return super.visitClass(node, v);
            } finally {
                if (named) {
                    owners.pop();
                }
            }
        }

        @Override
        public Void visitMethod(MethodTree node, Void v) {
            boolean prev = inConstructor;
            inConstructor = node.getName().contentEquals("<init>");
            try {
                return super.visitMethod(node, v);
            } finally {
                inConstructor = prev;
            }
        }

        @Override
        public Void visitVariable(VariableTree node, Void v) {
            Element e = trees.getElement(getCurrentPath());
            if (e != null) {
                switch (e.getKind()) {
                    case LOCAL_VARIABLE, EXCEPTION_PARAMETER, RESOURCE_VARIABLE -> dep(e.asType(), "local");
                    case FIELD -> {
                        if (isNew(node.getInitializer())) {
                            creates.add(fieldKey(e));
                        }
                    }
                    default -> { }
                }
            }
            return super.visitVariable(node, v);
        }

        @Override
        public Void visitAssignment(AssignmentTree node, Void v) {
            if (inConstructor && !owners.isEmpty() && isNew(node.getExpression())) {
                Element lhs = trees.getElement(new TreePath(getCurrentPath(), node.getVariable()));
                if (lhs != null && lhs.getKind() == ElementKind.FIELD
                        && lhs.getEnclosingElement().equals(owners.peek())) {
                    creates.add(fieldKey(lhs));
                }
            }
            return super.visitAssignment(node, v);
        }

        @Override
        public Void visitNewClass(NewClassTree node, Void v) {
            TypeMirror t = trees.getTypeMirror(new TreePath(getCurrentPath(), node.getIdentifier()));
            if (t != null) {
                dep(t, "new");
            }
            return super.visitNewClass(node, v);
        }

        @Override
        public Void visitMethodInvocation(MethodInvocationTree node, Void v) {
            if (node.getMethodSelect() instanceof MemberSelectTree ms) {
                TypeMirror recv = trees.getTypeMirror(new TreePath(getCurrentPath(), ms.getExpression()));
                if (recv != null && recv.getKind() == TypeKind.DECLARED) {
                    Element re = types.asElement(recv);
                    if (re instanceof TypeElement te) {
                        depOn(te, "call");
                    }
                }
            }
            return super.visitMethodInvocation(node, v);
        }

        @Override
        public Void visitMemberReference(MemberReferenceTree node, Void v) {
            Element e = trees.getElement(getCurrentPath());
            if (e != null && e.getEnclosingElement() instanceof TypeElement te) {
                depOn(te, "call");
            }
            return super.visitMemberReference(node, v);
        }

        @Override
        public Void visitMemberSelect(MemberSelectTree node, Void v) {
            staticRef(trees.getElement(getCurrentPath()));
            return super.visitMemberSelect(node, v);
        }

        @Override
        public Void visitIdentifier(IdentifierTree node, Void v) {
            staticRef(trees.getElement(getCurrentPath()));
            return super.visitIdentifier(node, v);
        }

        @Override
        public Void visitTypeCast(TypeCastTree node, Void v) {
            TypeMirror t = trees.getTypeMirror(new TreePath(getCurrentPath(), node.getType()));
            if (t != null) {
                dep(t, "cast");
            }
            return super.visitTypeCast(node, v);
        }

        @Override
        public Void visitInstanceOf(InstanceOfTree node, Void v) {
            if (node.getType() != null) {
                TypeMirror t = trees.getTypeMirror(new TreePath(getCurrentPath(), node.getType()));
                if (t != null) {
                    dep(t, "instanceof");
                }
            }
            return super.visitInstanceOf(node, v);
        }

        /** Static field or enum constant used through its type, e.g. CustomerState.WAITING. */
        private void staticRef(Element e) {
            if (e instanceof VariableElement
                    && (e.getKind() == ElementKind.ENUM_CONSTANT
                        || (e.getKind() == ElementKind.FIELD && e.getModifiers().contains(Modifier.STATIC)))
                    && e.getEnclosingElement() instanceof TypeElement te) {
                depOn(te, "static");
            }
        }

        private void dep(TypeMirror t, String reason) {
            if (!owners.isEmpty()) {
                addDeps(owners.peek(), t, reason);
            }
        }

        private void depOn(TypeElement target, String reason) {
            if (!owners.isEmpty()) {
                addDep(owners.peek(), target, reason);
            }
        }
    }

    private static boolean isNew(ExpressionTree e) {
        while (e instanceof ParenthesizedTree p) {
            e = p.getExpression();
        }
        return e instanceof NewClassTree || e instanceof NewArrayTree;
    }

    private static String fieldKey(Element field) {
        return name((TypeElement) field.getEnclosingElement()) + "#" + field.getSimpleName();
    }

    // ---------------------------------------------------------- dependencies

    private static void collectSignatureDeps(TypeElement t) {
        for (Element m : t.getEnclosedElements()) {
            if (m instanceof ExecutableElement ex && isExplicit(ex)) {
                addDeps(t, ex.getReturnType(), "return");
                ex.getParameters().forEach(p -> addDeps(t, p.asType(), "param"));
                ex.getThrownTypes().forEach(tt -> addDeps(t, tt, "throws"));
            }
        }
    }

    private static void addDeps(TypeElement owner, TypeMirror t, String reason) {
        for (TypeElement target : projectTypesIn(t)) {
            addDep(owner, target, reason);
        }
    }

    private static void addDep(TypeElement owner, TypeElement target, String reason) {
        if (!project.contains(target) || owner.equals(target)) {
            return;
        }
        deps.computeIfAbsent(name(owner), k -> new TreeMap<>())
                .computeIfAbsent(name(target), k -> new TreeSet<>())
                .add(reason);
    }

    /** Every project type mentioned in a type, including inside generics and arrays. */
    private static Set<TypeElement> projectTypesIn(TypeMirror t) {
        Set<TypeElement> found = new LinkedHashSet<>();
        collect(t, found);
        return found;
    }

    private static void collect(TypeMirror t, Set<TypeElement> found) {
        if (t == null) {
            return;
        }
        switch (t.getKind()) {
            case ARRAY -> collect(((ArrayType) t).getComponentType(), found);
            case WILDCARD -> {
                collect(((WildcardType) t).getExtendsBound(), found);
                collect(((WildcardType) t).getSuperBound(), found);
            }
            case DECLARED -> {
                DeclaredType dt = (DeclaredType) t;
                if (dt.asElement() instanceof TypeElement te && project.contains(te)) {
                    found.add(te);
                }
                dt.getTypeArguments().forEach(a -> collect(a, found));
            }
            default -> { }
        }
    }

    // ---------------------------------------------------------------- output

    private static void writeType(StringBuilder out, TypeElement t) {
        out.append("== ").append(t.getQualifiedName()).append("  <<").append(stereotype(t)).append(">>");
        String loc = location(t);
        if (loc != null) {
            out.append("   (").append(loc).append(")");
        }
        out.append('\n');

        out.append("   extends:    ").append(supers(t)).append('\n');
        String impl = t.getInterfaces().stream().map(AstRunner::show).collect(Collectors.joining(", "));
        if (t.getKind() != ElementKind.INTERFACE) {
            out.append("   implements: ").append(impl.isEmpty() ? "-" : impl).append('\n');
        }

        List<String> constants = new ArrayList<>();
        List<String> fields = new ArrayList<>();
        List<String> ctors = new ArrayList<>();
        List<String> methods = new ArrayList<>();
        List<String> nested = new ArrayList<>();
        for (Element m : t.getEnclosedElements()) {
            switch (m.getKind()) {
                case ENUM_CONSTANT -> constants.add(m.getSimpleName().toString());
                case FIELD -> {
                    String line = vis(m) + " " + m.getSimpleName() + " : " + show(m.asType()) + tags(m);
                    if (creates.contains(fieldKey(m))) {
                        line += " [creates]";
                    }
                    fields.add(line);
                }
                case CONSTRUCTOR -> {
                    if (isExplicit(m)) {
                        ctors.add(vis(m) + " " + t.getSimpleName() + params((ExecutableElement) m) + tags(m));
                    }
                }
                case METHOD -> {
                    if (isExplicit(m)) {
                        ExecutableElement ex = (ExecutableElement) m;
                        String line = vis(m) + " " + m.getSimpleName() + params(ex) + " : " + show(ex.getReturnType())
                                + tags(m);
                        if (!ex.getThrownTypes().isEmpty()) {
                            line += " throws " + ex.getThrownTypes().stream().map(AstRunner::show)
                                    .collect(Collectors.joining(", "));
                        }
                        methods.add(line);
                    }
                }
                case CLASS, INTERFACE, ENUM, RECORD, ANNOTATION_TYPE -> nested.add(name((TypeElement) m));
                default -> { }
            }
        }

        if (!constants.isEmpty()) {
            out.append("   enum constants: ").append(String.join(", ", constants)).append('\n');
        }
        section(out, "fields", fields);
        section(out, "constructors", ctors);
        section(out, "methods", methods);
        if (!nested.isEmpty()) {
            out.append("   nested types: ").append(String.join(", ", nested)).append('\n');
        }
        out.append('\n');
    }

    private static void section(StringBuilder out, String title, List<String> lines) {
        out.append("   ").append(title).append(":");
        if (lines.isEmpty()) {
            out.append(" -\n");
            return;
        }
        out.append('\n');
        lines.forEach(l -> out.append("     ").append(l).append('\n'));
    }

    private static int writeRelationships(StringBuilder out, List<TypeElement> sorted) {
        List<String[]> generalization = new ArrayList<>();
        List<String[]> realization = new ArrayList<>();
        List<String[]> association = new ArrayList<>();
        List<String[]> dependency = new ArrayList<>();
        List<String[]> nesting = new ArrayList<>();
        Set<String> linked = new HashSet<>();

        for (TypeElement t : sorted) {
            String me = name(t);
            if (t.getSuperclass() instanceof DeclaredType sup && project.contains(sup.asElement())) {
                generalization.add(new String[] {me + " --|> " + name((TypeElement) sup.asElement()), ""});
                linked.add(me + ">" + name((TypeElement) sup.asElement()));
            }
            for (TypeMirror i : t.getInterfaces()) {
                if (types.asElement(i) instanceof TypeElement ie && project.contains(ie)) {
                    boolean isExtends = t.getKind() == ElementKind.INTERFACE;
                    (isExtends ? generalization : realization).add(
                            new String[] {me + (isExtends ? " --|> " : " ..|> ") + name(ie), ""});
                    linked.add(me + ">" + name(ie));
                }
            }
            for (Element m : t.getEnclosedElements()) {
                if (m.getKind() == ElementKind.FIELD) {
                    for (TypeElement target : projectTypesIn(m.asType())) {
                        String mult = multiplicity(m.asType(), target);
                        String detail = "[field " + m.getSimpleName() + " : " + show(m.asType()) + ", " + mult + "]"
                                + (m.getModifiers().contains(Modifier.STATIC) ? " {static}" : "")
                                + (creates.contains(fieldKey(m)) ? " [creates]" : "");
                        association.add(new String[] {me + " --> " + name(target), detail});
                        linked.add(me + ">" + name(target));
                    }
                }
                if (m instanceof TypeElement inner && project.contains(inner)) {
                    nesting.add(new String[] {me + " +-- " + name(inner), ""});
                }
            }
        }
        deps.forEach((owner, targets) -> targets.forEach((target, reasons) -> {
            if (!linked.contains(owner + ">" + target)) {
                dependency.add(new String[] {owner + " ..> " + target, "[" + String.join(", ", reasons) + "]"});
            }
        }));

        out.append("== RELATIONSHIPS\n");
        int n = 0;
        n += relSection(out, "Generalization (extends)", generalization);
        n += relSection(out, "Realization (implements)", realization);
        n += relSection(out, "Association (field of project type)", association);
        n += relSection(out, "Dependency (used but not stored as a field)", dependency);
        n += relSection(out, "Nesting (member types)", nesting);
        return n;
    }

    private static int relSection(StringBuilder out, String title, List<String[]> rows) {
        out.append("-- ").append(title).append('\n');
        if (rows.isEmpty()) {
            out.append("   (none)\n");
            return 0;
        }
        int width = rows.stream().mapToInt(r -> r[0].length()).max().orElse(0);
        for (String[] r : rows) {
            String line = "   " + (r[1].isEmpty() ? r[0] : String.format("%-" + width + "s  %s", r[0], r[1]));
            out.append(line.stripTrailing()).append('\n');
        }
        return rows.size();
    }

    // --------------------------------------------------------------- helpers

    /** Implicit members (default constructor, enum values()/valueOf()) are not part of the design. */
    private static boolean isExplicit(Element e) {
        if (elements.getOrigin(e) != Elements.Origin.EXPLICIT) {
            return false;
        }
        if (e.getEnclosingElement().getKind() == ElementKind.ENUM && e instanceof ExecutableElement ex
                && ex.getModifiers().contains(Modifier.STATIC)) {
            String n = ex.getSimpleName().toString();
            int arity = ex.getParameters().size();
            return !((n.equals("values") && arity == 0) || (n.equals("valueOf") && arity == 1));
        }
        return true;
    }

    private static String stereotype(TypeElement t) {
        Set<Modifier> mods = t.getModifiers();
        String prefix = t.getNestingKind() == NestingKind.MEMBER && mods.contains(Modifier.STATIC)
                && t.getKind() == ElementKind.CLASS ? "static " : "";
        switch (t.getKind()) {
            case INTERFACE: return "interface";
            case ENUM: return "enum";
            case RECORD: return "record";
            case ANNOTATION_TYPE: return "annotation";
            default:
                if (mods.contains(Modifier.ABSTRACT)) return prefix + "abstract class";
                if (mods.contains(Modifier.FINAL)) return prefix + "final class";
                return prefix + "class";
        }
    }

    private static String supers(TypeElement t) {
        if (t.getKind() == ElementKind.INTERFACE) {
            String s = t.getInterfaces().stream().map(AstRunner::show).collect(Collectors.joining(", "));
            return s.isEmpty() ? "-" : s;
        }
        TypeMirror sup = t.getSuperclass();
        if (sup.getKind() != TypeKind.DECLARED) {
            return "-";
        }
        String q = ((TypeElement) types.asElement(sup)).getQualifiedName().toString();
        if (q.equals("java.lang.Object") || q.equals("java.lang.Enum") || q.equals("java.lang.Record")) {
            return "-";
        }
        return show(sup);
    }

    /** 1 for a plain field, 0..1 for Optional, 0..* for collections/maps/arrays, else "via generic". */
    private static String multiplicity(TypeMirror t, TypeElement target) {
        if (t.getKind() == TypeKind.DECLARED && target.equals(types.asElement(t))) {
            return "1";
        }
        if (t.getKind() == TypeKind.ARRAY) {
            return "0..*";
        }
        if (t.getKind() == TypeKind.DECLARED) {
            if (isA(t, "java.util.Optional")) {
                return "0..1";
            }
            if (isA(t, "java.util.Collection") || isA(t, "java.util.Map") || isA(t, "java.lang.Iterable")) {
                return "0..*";
            }
        }
        return "via generic " + show(types.erasure(t));
    }

    private static boolean isA(TypeMirror t, String qualified) {
        TypeElement te = elements.getTypeElement(qualified);
        return te != null && types.isSubtype(types.erasure(t), types.erasure(te.asType()));
    }

    private static String vis(Element e) {
        Set<Modifier> m = e.getModifiers();
        if (m.contains(Modifier.PUBLIC)) return "+";
        if (m.contains(Modifier.PRIVATE)) return "-";
        if (m.contains(Modifier.PROTECTED)) return "#";
        return "~";
    }

    private static String tags(Element e) {
        List<String> tags = new ArrayList<>();
        Set<Modifier> m = e.getModifiers();
        if (m.contains(Modifier.STATIC)) tags.add("{static}");
        if (m.contains(Modifier.FINAL)) tags.add("{final}");
        if (m.contains(Modifier.ABSTRACT) && e.getEnclosingElement().getKind() != ElementKind.INTERFACE) {
            tags.add("{abstract}");
        }
        if (m.contains(Modifier.DEFAULT)) tags.add("{default}");
        if (m.contains(Modifier.SYNCHRONIZED)) tags.add("{synchronized}");
        return tags.isEmpty() ? "" : " " + String.join(" ", tags);
    }

    private static String params(ExecutableElement ex) {
        List<String> ps = new ArrayList<>();
        List<? extends VariableElement> params = ex.getParameters();
        for (int i = 0; i < params.size(); i++) {
            VariableElement p = params.get(i);
            String type = show(p.asType());
            if (ex.isVarArgs() && i == params.size() - 1 && type.endsWith("[]")) {
                type = type.substring(0, type.length() - 2) + "...";
            }
            ps.add(p.getSimpleName() + " : " + type);
        }
        return "(" + String.join(", ", ps) + ")";
    }

    /** Type as written, with package prefixes dropped: java.util.List<rush.model.Order> -> List<Order>. */
    private static String show(TypeMirror t) {
        return t.toString().replaceAll("\\b(?:[a-z_][\\w$]*\\.)+(?=[A-Z])", "").replace(",", ", ");
    }

    /** Project type name without its package, keeping the outer class for nested types. */
    private static String name(TypeElement t) {
        String q = t.getQualifiedName().toString();
        String pkg = elements.getPackageOf(t).getQualifiedName().toString();
        return pkg.isEmpty() ? q : q.substring(pkg.length() + 1);
    }

    private static String location(TypeElement t) {
        TreePath path = trees.getPath(t);
        if (path == null) {
            return null;
        }
        CompilationUnitTree cu = path.getCompilationUnit();
        Tree leaf = path.getLeaf();
        long pos = trees.getSourcePositions().getStartPosition(cu, leaf);
        Path file = Paths.get(cu.getSourceFile().toUri());
        Path cwd = Paths.get("").toAbsolutePath();
        String shown = file.startsWith(cwd) ? slash(cwd.relativize(file)) : slash(file);
        return shown + ":" + cu.getLineMap().getLineNumber(pos);
    }

    private static String slash(Path p) {
        return p.toString().replace('\\', '/');
    }
}
